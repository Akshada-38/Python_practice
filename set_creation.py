# Create set using set() method :
set_from_list = set([1, 2, 3, 4, 5])
print("Set created from list:", set_from_list)  

# Create set using curly braces :
set_with_curly_braces = {10, 20, 30, 40, 50}
print("Set created with curly braces:", set_with_curly_braces)

# Create set using string :
set_from_string = set("Hello")
print("Set created from string:", set_from_string)

# Create empty set :
empty_set = set()
print("Empty set:", empty_set)


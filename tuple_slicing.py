name = ("Riya", "Pooja", "Sakshi", "Ankita ", "Neha", "Sneha")
#Slicing the tuple to get the third to fifth elements using negative indexing
sliced_tuple = name[-4:-1]
print("The sliced tuple from third to fifth elements is :", sliced_tuple)

#Slicing the tuple to get the first to third elements using positive indexing
sliced_tuple_positive = name[0:3]   
print("The sliced tuple from first to third elements is :", sliced_tuple_positive)
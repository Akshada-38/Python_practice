# for checking if an item exists in a tuple using 'in' keyword
name = ("Sakshi", "Ankita", "Riya", "Pooja")
# Checking if "Riya" exists in the tuple
item_exists = "Riya" in name    
print("Is 'Riya' present in the tuple?:", item_exists)
not_exists = "Neha" in name
print("Is 'Neha' present in the tuple?:", not_exists)
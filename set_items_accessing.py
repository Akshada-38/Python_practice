data = {"Priyal" , 12.5 , "Shivam" , 123 , "Satyarth" , True , 5 + 3j}
# Accessing items from the set using a loop
for item in data:
    print("The item is:", item)
print("the set(data) is accessed successfully")

#In set, we canot access items using index because sets are unordered and do not support indexing. However, we can access items using a loop or by checking for the presence of an item in the set.
# Create tuples using tuple() method :
tuple_from_list = tuple([1, 2, 3, 4, 5])    
print("Tuple created from list:", tuple_from_list)

# Create tuples using string :
tuple_from_string = tuple("Hello")
print("Tuple created from string:", tuple_from_string)

# Create tuples using parentheses :
tuple_with_parentheses = (10, 20, 30, 40, 50)
print("Tuple created with parentheses:", tuple_with_parentheses)

# Create single element tuple :
single_element_tuple = (100,)
print("Single element tuple:", single_element_tuple)# Note: Tuples are immutable, so to update a tuple, we need to convert it to a list first.